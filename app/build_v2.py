"""Build design 2 (burgundy & gold) from design 1 by re-theming colours.
Run after editing v1:  python3 build_v2.py
shortcut: plain colour find/replace; if v2 needs different layouts, fork v2/app.js instead.
"""
import pathlib, re

HERE = pathlib.Path(__file__).parent
V1, V2 = HERE / 'v1', HERE / 'v2'
V2.mkdir(exist_ok=True)

# v1 colour -> v2 colour (case-insensitive)
MAP = {
    # brand green -> deep burgundy
    '#2E3A2C': '#4A1014', '#3E4D3B': '#6A1A20', '#1C251B': '#240709',
    'rgba(46,58,44': 'rgba(74,16,20',
    # ember CTA -> wine red
    '#B8492B': '#8E1F26', '#9E3C22': '#6E161C', 'rgba(184,73,43': 'rgba(142,31,38', '#F4D9CB': '#F1CFCB',
    # warm gold accents -> logo gold
    '#E9B87A': '#D9AE62', 'rgba(233,184,122': 'rgba(217,174,98', '#B48A52': '#B0823F',
    # ivory surfaces (slightly rosier)
    '#F4EEE4': '#F7F0E8', '#FFFCF7': '#FFFBF7', '#EAE0CF': '#EEDFD3', '#E4D9C8': '#E9D9CD',
    '#EFE8DC': '#F1E6DE', '#E9E2D6': '#ECE1D8', '#D9CFBF': '#DCCBC0', '#E4DACA': '#EAD8CE',
    '#E3DACB': '#E8D8CD', '#D6CBBB': '#DCC9BE', '#CDBFAC': '#D3BDB2', '#D3C6B4': '#D8C3B8', '#C3B49F': '#C9AFA4',
    # inks
    '#1F1A16': '#2A1215', '#4A4038': '#55383A', '#8A7C6E': '#8E7470',
    # dark screens
    '#16120F': '#240709', 'rgba(22,18,15': 'rgba(36,7,9', 'rgba(18,14,11': 'rgba(30,6,8', 'rgba(31,26,22': 'rgba(42,18,21',
    '#221C18': '#3A1416', '#33291F': '#4F1E21', '#B7AA9B': '#CDAFAA', '#CBBFB1': '#DCC4BF', '#7D7062': '#9A7A76', '#4A3F36': '#5A2A2E',
    # soft greens -> soft rose
    '#EEF1EA': '#F7E9E5', '#E2E9DD': '#F4E2DC', '#CFD6C9': '#E9CCC6', '#3F7A4E': '#3F7A4E',
}

def retheme(text):
    for a, b in MAP.items():
        text = re.sub(re.escape(a), b, text, flags=re.I)
    return text

css = retheme((V1 / 'app.css').read_text(encoding='utf8'))
# headings in the logo's typeface instead of Ruqaa
css = css.replace("--fd:'Aref Ruqaa',serif;", "--fd:'El Messiri',serif;")
css += "\n/* v2: El Messiri headings are wider than Ruqaa */\n.onb-copy h2{font-size:34px;line-height:1.35}.hero h2{font-size:28px}.title.ruqaa{font-size:32px}\n"
(V2 / 'app.css').write_text(css, encoding='utf8')

js = retheme((V1 / 'app.js').read_text(encoding='utf8'))
js = js.replace("Sinam — interactive app prototype, design 1", "Sinam — interactive app prototype, design 2 (generated by build_v2.py)")
(V2 / 'app.js').write_text(js, encoding='utf8')

html = retheme((V1 / 'index.html').read_text(encoding='utf8'))
html = html.replace('التصميم الأول', 'التصميم الثاني').replace('content="#240709"', 'content="#4A1014"')
(V2 / 'index.html').write_text(html, encoding='utf8')
print('built v2')
